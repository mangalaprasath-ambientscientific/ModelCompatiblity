// FRAME SLIDER  (draggable; snaps to whole 32 ms frames)
// =====================================================
function FrameSlider({ value, min, max, onChange, tip, avoidRef }) {
  const trackRef = useRef(null);
  const tipRef = useRef(null);
  const [dragging, setDragging] = useState(false);
  const [tipBelow, setTipBelow] = useState(false);
 
  const v = Math.max(min, Math.min(max, value));
  const pct = ((v - min) / (max - min)) * 100;
 
  // Tooltip sits above the thumb, except where that would cover the 1s..5s
  // preset buttons — there it flips below. avoidRef is the button row; measure
  // the buttons themselves (their flex parent stretches the full column width).
  useEffect(() => {
    const track = trackRef.current;
    const tipEl = tipRef.current;
    const row = avoidRef && avoidRef.current;
    if (!track || !tipEl || !row) return;
 
    const decide = () => {
      const kids = Array.from(row.children);
      if (!kids.length) return setTipBelow(false);
 
      const rects = kids.map((k) => k.getBoundingClientRect());
      const btnLeft = Math.min(...rects.map((r) => r.left));
      const btnRight = Math.max(...rects.map((r) => r.right));
 
      const t = track.getBoundingClientRect();
      const half = (tipEl.offsetWidth || 46) / 2 + 4;   // +4px breathing room
      const cx = t.left + (pct / 100) * t.width;
 
      setTipBelow(cx + half > btnLeft && cx - half < btnRight);
    };
 
    decide();
    window.addEventListener("resize", decide);
    return () => window.removeEventListener("resize", decide);
  }, [pct, tip, avoidRef]);
 
  const valueFromX = useCallback(
    (clientX) => {
      const el = trackRef.current;
      if (!el) return v;
      const r = el.getBoundingClientRect();
      const ratio = Math.min(1, Math.max(0, (clientX - r.left) / r.width));
      return Math.round(min + ratio * (max - min));
    },
    [min, max, v]
  );
 
  const down = (e) => {
    e.preventDefault();
    setDragging(true);
    e.currentTarget.setPointerCapture?.(e.pointerId);
    onChange(valueFromX(e.clientX));
  };
  const move = (e) => {
    if (dragging) onChange(valueFromX(e.clientX));
  };
  const up = (e) => {
    setDragging(false);
    e.currentTarget.releasePointerCapture?.(e.pointerId);
  };
  const key = (e) => {
    const clamp = (n) => Math.max(min, Math.min(max, n));
    let next = null;
    if (e.key === "ArrowRight" || e.key === "ArrowUp") next = v + 1;
    else if (e.key === "ArrowLeft" || e.key === "ArrowDown") next = v - 1;
    else if (e.key === "PageUp") next = v + 8;
    else if (e.key === "PageDown") next = v - 8;
    else if (e.key === "Home") next = min;
    else if (e.key === "End") next = max;
    if (next !== null) {
      e.preventDefault();
      onChange(clamp(next));
    }
  };
 
  const stepTick = max - min > 80 ? 2 : 1;
  const ticks = [];
  for (let i = min; i <= max; i += stepTick) {
    const p = ((i - min) / (max - min)) * 100;
    ticks.push(
      <span
        key={i}
        className={
          "pp-cap-tick" + (i <= v ? " on" : "") + ((i - min) % 5 === 0 ? " major" : "")
        }
        style={{ left: p + "%" }}
      />
    );
  }
 
  return (
    <div
      ref={trackRef}
      className={"pp-cap-track" + (dragging ? " dragging" : "")}
      onPointerDown={down}
      onPointerMove={move}
      onPointerUp={up}
      onPointerCancel={up}
    >
      <div className="pp-cap-tickrow">{ticks}</div>
      <div className="pp-cap-fill" style={{ width: pct + "%" }} />
      <div
        className="pp-cap-thumb"
        style={{ left: pct + "%" }}
        role="slider"
        tabIndex={0}
        aria-label="Capture length in 32 ms frames"
        aria-valuemin={min}
        aria-valuemax={max}
        aria-valuenow={v}
        aria-valuetext={tip}
        onKeyDown={key}
      >
        <span className={"pp-cap-tip" + (tipBelow ? " below" : "")} ref={tipRef}>{tip}</span>
      </div>
    </div>
  );
}
 
 

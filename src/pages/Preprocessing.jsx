const KEYWORDS = new Set([
  "def", "return", "for", "in", "import", "from", "as", "if", "else",
  "elif", "while", "and", "or", "not", "class", "with", "lambda",
  "None", "True", "False", "pass", "yield",
]);
 
const BUILTINS = new Set([
  "np", "print", "range", "len", "int", "float", "self", "zip",
  "max", "min", "enumerate", "list",
]);
 
function esc(text) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}
 
function highlight(code) {
  const re = /("""[\s\S]*?"""|'''[\s\S]*?'''|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')|(#.*$)|\b(0x[0-9a-fA-F]+|\d+\.?\d*)\b|\b([A-Za-z_]\w*)\b/gm;
 
  let out = "";
  let last = 0;
  let m;
 
  while ((m = re.exec(code))) {
    out += esc(code.slice(last, m.index));
 
    if (m[1]) {
      out += '<span class="pp-str">' + esc(m[1]) + "</span>";
    } else if (m[2]) {
      out += '<span class="pp-com">' + esc(m[2]) + "</span>";
    } else if (m[3]) {
      out += '<span class="pp-num">' + esc(m[3]) + "</span>";
    } else if (m[4]) {
      const word = m[4];
      if (KEYWORDS.has(word)) {
        out += '<span class="pp-kw">' + word + "</span>";
      } else if (BUILTINS.has(word)) {
        out += '<span class="pp-bi">' + word + "</span>";
      } else {
        const before = code.slice(0, m.index);
        if (/def\s+$/.test(before)) {
          out += '<span class="pp-def">' + word + "</span>";
        } else {
          out += word;
        }
      }
    }
 
    last = re.lastIndex;
  }
 
  out += esc(code.slice(last));
 
  return out
    .split("\n")
    .map((line, i) => '<span class="pp-ln">' + (i + 1) + "</span>" + line)
    .join("\n");
}
 
 

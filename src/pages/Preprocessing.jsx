const SAMPLE_RATE = 8000;  // Hz — 1 sample = 0.125 ms
const FRAME_LEN = 256;   // samples per frame = 32 ms
const MIN_FRAMES = 1;     // 1 frame  = 256 samples = 32 ms
const MAX_SECONDS = 5;     // hard cap: 5 s of audio
const MAX_FRAMES = Math.floor((MAX_SECONDS * SAMPLE_RATE) / FRAME_LEN); // 156 frames ≈ 4.992 s
 
// Static procedural waveform for the frame-tiling strip (scaled by viewBox).
const WAVE = (() => {
  const N = 240, W = 1000, H = 64, mid = H / 2, amp = 22;
  let pts = "";
  for (let i = 0; i < N; i++) {
    const t = i / (N - 1);
    const env = Math.pow(Math.sin(Math.PI * t), 0.75);
    let y =
      Math.sin(t * 20 * Math.PI) * 0.55 +
      Math.sin(t * 47 * Math.PI + 1) * 0.24 +
      Math.sin(t * 97 * Math.PI + 2) * 0.13;
    y *= env;
    pts += (i ? " " : "") + (t * W).toFixed(1) + "," + (mid - y * amp).toFixed(1);
  }
  return { pts, W, H };
})();
 
 

function buildFullCode(state) {
  const nf = state.features;
  const cap = state.capture;
  const frames = Math.max(0, Math.floor(cap / state.frame));
  const ms = ((cap / SAMPLE_RATE) * 1000).toFixed(0);
  const bar = "=".repeat(70);
  const L = [];
 
  // ----- File header -----
  L.push("# " + bar);
  L.push("# Ambient Scientific  -  GPX audio front-end  (FULL feature pipeline)");
  L.push("# Auto-generated by the Pre-Processing Pipeline Studio");
  L.push("#");
  L.push("# Selected path       : FFT -> Square -> Shift -> Saturate -> Mel -> Accumulate -> Log");
  L.push("# Features (num_filt) : " + nf);
  L.push("# Capture length      : " + cap + " samples  (" + frames + " frame" + (frames === 1 ? "" : "s") + " of " + state.frame + " = " + ms + " ms @ 8 kHz)");
  L.push("# Source of truth      : Feature-Extraction.py  (frames2feature)");
  L.push("# " + bar);
  L.push("");
  L.push("import numpy as np");
  L.push("");
 
  // ----- Tweakable hardware parameters -----
  L.push("# ----- Tweakable hardware parameters ---------------------------------");
  L.push("SAMPLE_RATE = 8000" + pad(8000) + "# audio sample rate (Hz)");
  L.push("FRAME_SIZE  = " + state.frame + pad(state.frame) + "# samples per FFT frame  (HW FIFO depth = 256 = 32 ms)");
  L.push("CAPTURE_LEN = " + cap + pad(cap) + "# total samples/clip: " + frames + " frames x 256 (32 ms each)");
  L.push("NUM_FILT    = " + nf + pad(nf) + "# mel features emitted per frame");
  L.push("FFT_SHIFT   = " + state.fftShift + pad(state.fftShift) + "# real-FFT output right-shift  (>> " + state.fftShift + ")");
  L.push("SQR_SHIFT   = " + state.sqrShift + pad(state.sqrShift) + "# post-square right-shift      (>> " + state.sqrShift + ")");
  L.push("SAT_MAX     = " + state.satMax + pad(state.satMax) + "# saturation clamp value (int16 max)");
  L.push("# ---------------------------------------------------------------------");
  L.push("");
  L.push("");
 
  // ----- chop_array() -----
  L.push("def chop_array(arr, window_size, hop_size):");
  L.push('    """Slice a 1-D signal into non-overlapping frames (window == hop)."""');
  L.push("    return [arr[i - window_size:i]");
  L.push("            for i in range(window_size, len(arr) + 1, hop_size)]");
  L.push("");
  L.push("");
 
  // ----- safe_log() -----
  L.push("def safe_log(x):");
  L.push('    """log2 (matches the hardware log block)."""');
  L.push("    return np.log2(x)");
  L.push("");
  L.push("");
 
  // ----- filterbanks() -----
  L.push("def filterbanks(sample_rate, num_filt, fft_len):");
  L.push('    """Triangle filters on a mel grid, quantized to int8 weights (0..32)."""');
  L.push("    def hertz_to_mels(f):");
  L.push("        return 1127. * np.log(1. + f / 700.)");
  L.push("");
  L.push("    def mel_to_hertz(mel):");
  L.push("        return 700. * (np.exp(mel / 1127.) - 1.)");
  L.push("");
  L.push("    def correct_grid(x):");
  L.push('        """Push duplicate points forward so no filter has zero width."""');
  L.push("        offset = 0");
  L.push("        for prev, i in zip([x[0] - 1] + list(x), x):");
  L.push("            offset = max(0, offset + prev + 1 - i)");
  L.push("            yield i + offset");
  L.push("");
  L.push("    grid_mels    = np.linspace(hertz_to_mels(0), hertz_to_mels(sample_rate), num_filt + 2, True)");
  L.push("    grid_hertz   = mel_to_hertz(grid_mels)");
  L.push("    grid_indices = (grid_hertz * fft_len / sample_rate).astype(int)");
  L.push("    grid_indices = list(correct_grid(grid_indices))");
  L.push("");
  L.push("    banks = np.zeros([num_filt, fft_len])");
  L.push("    for i, (left, middle, right) in enumerate(chop_array(grid_indices, 3, 1)):");
  L.push("        banks[i, left:middle]  = np.linspace(0., 1., middle - left, False)");
  L.push("        banks[i, middle:right] = np.linspace(1., 0., right - middle, False)");
  L.push("    return banks");
  L.push("");
  L.push("");
 
  // ----- preprocess() -----
  L.push("def preprocess(audio):");
  L.push('    """Full GPX feature front-end in integer arithmetic.');
  L.push("");
  L.push("    FFT -> Square -> Shift -> Saturate -> Mel filterbank -> Accumulate -> Log");
  L.push('    """');
  L.push("    # pad / trim every clip to exactly CAPTURE_LEN samples");
  L.push("    audio = np.asarray(audio)");
  L.push("    if len(audio) < CAPTURE_LEN:");
  L.push('        audio = np.pad(audio, (0, CAPTURE_LEN - len(audio)), mode="constant")');
  L.push("    elif len(audio) > CAPTURE_LEN:");
  L.push("        audio = audio[-CAPTURE_LEN:]");
  L.push("");
  L.push("    frames   = np.short(chop_array(audio, FRAME_SIZE, FRAME_SIZE))");
  L.push("    filters  = filterbanks(SAMPLE_RATE, NUM_FILT, FRAME_SIZE)");
  L.push('    intfltrs = np.array(filters * 32).round().astype("int8")');
  L.push("");
  L.push("    output = []");
  L.push("    for frame in frames:");
  L.push("        frame = np.short(frame)");
  L.push("");
  L.push("        # --- FFT ------------------------------------------------------");
  L.push("        spec = np.fft.fft(frame)");
  L.push("        spec = np.int32(spec.real) >> FFT_SHIFT");
  L.push("        spec = np.short(spec)");
  L.push("");
  L.push("        # --- Square + Shift ------------------------------------------");
  L.push('        spec = spec.astype("int32") ** 2');
  L.push("        spec = spec >> SQR_SHIFT");
  L.push("");
  L.push("        # --- Saturate ------------------------------------------------");
  L.push("        spec[spec >= (SAT_MAX + 1)] = SAT_MAX");
  L.push("");
  L.push("        # --- Mel filterbank + Accumulate -----------------------------");
  L.push('        mels = np.dot(spec.astype("int32"), intfltrs.T.astype("int32"))');
  L.push("        mels = mels & 0xffff");
  L.push("");
  L.push("        # --- Log ------------------------------------------------------");
  L.push("        features = np.array(safe_log(mels), dtype=np.int16)");
  L.push("        output.append(features)");
  L.push("");
  L.push("    return output");
  L.push("");
  L.push("");
 
  // ----- demo entry point -----
  L.push('if __name__ == "__main__":');
  L.push("    dummy = np.random.randint(-2000, 2000, CAPTURE_LEN).astype(np.short)");
  L.push("    feats = preprocess(dummy)");
  L.push('    print("frames:", len(feats), "| features/frame:", NUM_FILT)');
 
  return L.join("\n");
}
 
 

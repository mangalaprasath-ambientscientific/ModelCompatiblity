// Right-pad a value with spaces so the trailing comments line up.
function pad(value) {
  const text = String(value);
  return " ".repeat(Math.max(1, 9 - text.length));
}
 
// ---------------------------------------------------------------------
// PATHS 01–03  —  preprocess() only (FFT / Square·Shift / Saturate)
// ---------------------------------------------------------------------
function buildCode(state) {
  const square = state.square;
  const saturate = state.saturate;
  const lines = [];
 
  const stages = [
    "FFT",
    square ? "Square" : null,
    square ? "Shift" : null,
    saturate ? "Saturate" : null,
  ].filter(Boolean);
 
  const bar = "=".repeat(70);
 
  // ----- File header -----
  lines.push("# " + bar);
  lines.push("# Ambient Scientific  -  GPX audio front-end (pre-processing)");
  lines.push("# Auto-generated by the Pre-Processing Pipeline Studio");
  lines.push("#");
  lines.push("# Selected hardware path : " + stages.join("  ->  "));
  lines.push("# Source of truth        : Feature-Extraction.py  (frames2feature)");
  lines.push("# " + bar);
  lines.push("");
  lines.push("import numpy as np");
  lines.push("");
 
  // ----- Tweakable hardware parameters -----
  lines.push("# ----- Tweakable hardware parameters ---------------------------------");
  lines.push("FRAME_SIZE = " + state.frame + pad(state.frame) + "# samples per FFT frame  (HW FIFO depth = 256)");
  lines.push("FFT_SHIFT  = " + state.fftShift + pad(state.fftShift) + "# real-FFT output right-shift   (>> " + state.fftShift + ")");
  if (square) {
    lines.push("SQR_SHIFT  = " + state.sqrShift + pad(state.sqrShift) + "# post-square right-shift       (>> " + state.sqrShift + ")");
  }
  if (saturate) {
    lines.push("SAT_MAX    = " + state.satMax + pad(state.satMax) + "# saturation clamp value (int16 max)");
  }
  lines.push("# ---------------------------------------------------------------------");
  lines.push("");
  lines.push("");
 
  // ----- chop_array() helper -----
  lines.push("def chop_array(arr, window_size, hop_size):");
  lines.push('    """Slice a 1-D signal into non-overlapping frames (window == hop)."""');
  lines.push("    return [arr[i - window_size:i]");
  lines.push("            for i in range(window_size, len(arr) + 1, hop_size)]");
  lines.push("");
  lines.push("");
 
  // ----- preprocess() -----
  lines.push("def preprocess(audio):");
  lines.push('    """Replicate the GPX hardware audio front-end in integer arithmetic.');
  lines.push("");
  lines.push("    Active stages:  " + stages.join("  ->  "));
  lines.push('    """');
  lines.push("    frames = np.short(chop_array(audio, FRAME_SIZE, FRAME_SIZE))");
  lines.push("    output = []");
  lines.push("");
  lines.push("    for frame in frames:");
  lines.push("        frame = np.short(frame)");
  lines.push("");
  lines.push("        # --- FFT (mandatory) -----------------------------------------");
  lines.push("        spec = np.fft.fft(frame)");
  lines.push("        spec = np.int32(spec.real)          # keep the real part");
  lines.push("        spec = spec >> FFT_SHIFT            # fixed-point rescale");
  lines.push("        spec = np.short(spec)");
 
if (!square) {
    lines.push("        output.append(spec)                # <-- FFT-only output");
  } else {
    lines.push("");
    lines.push("        # --- Square + Shift ------------------------------------------");
    lines.push('        spec = spec.astype("int32") ** 2    # power of each freq bin');
    lines.push("        spec = spec >> SQR_SHIFT           # rescale toward 16-bit");

    if (!saturate) {
      lines.push("");
      lines.push("        # --- HW output register is 16-bit signed--------------------");
      lines.push("        spec = np.array(spec & 0xFFFF, dtype=np.uint16).view(np.int16)");
      lines.push("");
      lines.push("        output.append(spec)                # <-- square+shift output (int16)");
    } else {
      lines.push("");
      lines.push("        # --- Saturate ------------------------------------------------");
      lines.push("        spec[spec > SAT_MAX] = 0xFFFF");
      lines.push("        spec = np.array(spec & 0xFFFF, dtype=np.uint16).view(np.int16)");
      lines.push("        output.append(spec)                # <-- saturated output");
    }
  }
 
  lines.push("");
  lines.push("    return output");
  lines.push("");
  lines.push("");
 
  // ----- demo entry point -----
  lines.push('if __name__ == "__main__":');
  lines.push("    dummy = np.random.randint(-2000, 2000, FRAME_SIZE).astype(np.short)");
  lines.push("    feats = preprocess(dummy)");
  lines.push('    print("frames:", len(feats), "| bins/frame:", np.asarray(feats).shape)');
 
  return lines.join("\n");
}
 
